"""Generate the icon artwork: a clock whose hand spins so fast it leaves a blur and ghost hands behind it.

Writes icons/icon.svg (48/128 px, with Chrome's 16 px margin), icons/icon-small.svg (16/32 px, full bleed) and
store/promo-small.svg (440x280 tile), then renders icons/icon-{16,32,48,128}.png with rsvg-convert.
The promo tile PNG is rendered by dev/store-assets.sh. Usage: python3 icons/build.py
"""
import math
import pathlib
import subprocess

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
TOP, BOTTOM = '#5548E6', '#3529B5'
HAND = -30  # degrees, SVG convention (0 = 3 o'clock, clockwise): the hand points at 2 o'clock and spins clockwise


def point(cx, cy, r, deg):
    a = math.radians(deg)
    return cx + r * math.cos(a), cy + r * math.sin(a)


def blur(cx, cy, r, span=110, layers=22, alpha=0.045):
    """Motion blur behind the hand. Every wedge starts at the hand and reaches back a different distance,
    so the layers stack into a smooth fade without the seams that side-by-side wedges leave."""
    out = []
    for i in range(1, layers + 1):
        back = span * i / layers
        (x1, y1), (x2, y2) = point(cx, cy, r, HAND - back), point(cx, cy, r, HAND)
        out.append(f'<path d="M{cx} {cy} L{x1:.2f} {y1:.2f} A{r} {r} 0 {int(back > 180)} 1 {x2:.2f} {y2:.2f} Z" '
                   f'fill="#fff" fill-opacity="{alpha}"/>')
    return out


def ghosts(cx, cy, length, width, trail):
    out = []
    for offset, opacity in trail:
        x, y = point(cx, cy, length, HAND + offset)
        out.append(f'<line x1="{cx}" y1="{cy}" x2="{x:.2f}" y2="{y:.2f}" stroke="#fff" stroke-opacity="{opacity}" '
                   f'stroke-width="{width}" stroke-linecap="round"/>')
    return out


def clock(cx, cy, s, small=False):
    """The mark at scale s (s=1: ring radius 35 in a 128 px icon)."""
    hx, hy = point(cx, cy, 25 * s if not small else 7.8, HAND)
    ring, ring_w, hand_w = (35 * s, 7 * s, 7 * s) if not small else (11, 2.8, 2.8)
    trail = [(-24, .55), (-48, .32), (-72, .16)] if not small else [(-30, .5), (-60, .22)]
    parts = blur(cx, cy, 29.5 * s if not small else 9.6)
    parts += ghosts(cx, cy, 23.5 * s if not small else 7.2, 5 * s if not small else 2.2, trail)
    parts += [f'<circle cx="{cx}" cy="{cy}" r="{ring:.2f}" fill="none" stroke="#fff" stroke-width="{ring_w:.2f}"/>',
              f'<line x1="{cx}" y1="{cy}" x2="{hx:.2f}" y2="{hy:.2f}" stroke="#fff" stroke-width="{hand_w:.2f}" stroke-linecap="round"/>',
              f'<circle cx="{cx}" cy="{cy}" r="{hand_w * 0.75:.2f}" fill="#fff"/>']
    return parts


def svg(width, height, body, comment, gradient=('0', '0', '0', '1')):
    x1, y1, x2, y2 = gradient
    inner = '\n  '.join(body)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">
  <!-- {comment} Generated by icons/build.py; edit that, not this. -->
  <defs>
    <linearGradient id="bg" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">
      <stop offset="0" stop-color="{TOP}"/>
      <stop offset="1" stop-color="{BOTTOM}"/>
    </linearGradient>
  </defs>
  {inner}
</svg>
'''


def main():
    (HERE / 'icon.svg').write_text(svg(128, 128,
        ['<rect x="16" y="16" width="96" height="96" rx="22" fill="url(#bg)"/>', *clock(64, 64, 1)],
        'Master icon for 48 and 128 px: 96 px tile inside the 16 px margin Chrome asks for.'))
    (HERE / 'icon-small.svg').write_text(svg(32, 32,
        ['<rect width="32" height="32" rx="7" fill="url(#bg)"/>', *clock(16, 16, 1, small=True)],
        'Toolbar sizes (16 and 32 px): full bleed, heavier strokes, fewer ghost hands.'))
    font = 'font-family="Helvetica Neue, Helvetica, Arial, sans-serif" fill="#fff"'
    (ROOT / 'store' / 'promo-small.svg').write_text(svg(440, 280, [
        '<rect width="440" height="280" fill="url(#bg)"/>',
        *clock(84, 100, 1.05),
        f'<text x="38" y="196" font-size="31" font-weight="700" {font}>Quick Time Log &amp; Edit</text>',
        f'<text x="38" y="228" font-size="18" fill-opacity="0.8" {font}>for Everhour on Trello</text>',
    ], 'Chrome Web Store small promo tile; dev/store-assets.sh renders it to promo-small-440x280.png.', ('0', '0', '1', '1')))
    for px, src in [(128, 'icon.svg'), (48, 'icon.svg'), (32, 'icon-small.svg'), (16, 'icon-small.svg')]:
        subprocess.run(['rsvg-convert', '-w', str(px), '-h', str(px), str(HERE / src), '-o', str(HERE / f'icon-{px}.png')], check=True)


if __name__ == '__main__':
    main()
